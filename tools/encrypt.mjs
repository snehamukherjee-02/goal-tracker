// Encrypts private/content.json  ->  content.enc.js  (safe to publish)
// Usage:  node tools/encrypt.mjs
// Your password is typed here only. It is never saved anywhere.

import { webcrypto as crypto } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import readline from "node:readline";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "private", "content.json");
const OUT = path.join(ROOT, "content.enc.js");
const ITER = 600000;

function askHidden(query) {
  return new Promise(resolve => {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
    rl.muted = false;
    rl._writeToOutput = s => {
      if (!rl.muted) rl.output.write(s);
      else if (!/[\r\n]/.test(s)) rl.output.write("*".repeat(s.length));
    };
    rl.question(query, answer => { rl.close(); process.stdout.write("\n"); resolve(answer); });
    rl.muted = true;
  });
}

const b64 = buf => Buffer.from(buf).toString("base64");

if (!fs.existsSync(SRC)) {
  console.error(`Not found: ${SRC}`);
  process.exit(1);
}
const plain = fs.readFileSync(SRC, "utf8");
JSON.parse(plain); // validate

// On GitHub Actions the password comes from the GOAL_PASSWORD secret; locally you type it.
let pw1 = process.env.GOAL_PASSWORD;
if (pw1) {
  pw1 = pw1.trim();
} else {
  pw1 = await askHidden("Choose your password (12+ characters recommended): ");
  const pw2 = await askHidden("Type it again: ");
  if (pw1 !== pw2) { console.error("Passwords don't match. Nothing was changed."); process.exit(1); }
}
if (pw1.length < 8) { console.error("Too short. Use at least 8 characters (12+ is much safer)."); process.exit(1); }

const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(pw1), "PBKDF2", false, ["deriveKey"]);
const key = await crypto.subtle.deriveKey(
  { name: "PBKDF2", salt, iterations: ITER, hash: "SHA-256" },
  base, { name: "AES-GCM", length: 256 }, false, ["encrypt"]
);
const data = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, new TextEncoder().encode(plain));

const payload = { v: 1, iter: ITER, salt: b64(salt), iv: b64(iv), data: b64(data) };
fs.writeFileSync(OUT,
  "// Encrypted content (AES-256-GCM). Generated by tools/encrypt.mjs. Do not edit.\n" +
  `window.ENCRYPTED_CONTENT = ${JSON.stringify(payload)};\n`);

console.log(`✅ Encrypted! Wrote ${path.relative(ROOT, OUT)}`);
console.log("Remember your password. If you forget it, nobody can unlock the content (not even Claude).");
